"""
prepare_training_pool_v2.py — Build data/training_pool_v2.csv (TRAINING data)
=============================================================================

Combines three sources, none derived from the frozen evaluation set's
sources (Mishra & Soni 2022 / UCI SMS Spam / NUS SMS Corpus):

  SYN   data/synthetic_financial_messages_v1.csv — this project's synthetic
        templates (both labels). Group = template family.
  R115  Ridham115/indian-scam-sms-synthetic-audited (Hugging Face, CC BY 4.0),
        revision 45e92c38… — LLM-generated Indian scam/safe SMS with an
        intent-based rubric (label_rubric.md). Only rows generated by
        groq/openai/gpt-oss-120b are used; Gemini-generated rows are excluded
        pending review of the generator provider's output terms.
        scam -> suspicious, safe -> legitimate. Group = label:topic:language
        (the generation batch target).
  MWOZ  MultiWOZ 2.2 (github.com/budzianowski/multiwoz, MIT, commit fe0c8e65…),
        train/dialogues_001.json — human-written Wizard-of-Oz booking
        dialogues. Benign by construction -> legitimate. One USER and one
        SYSTEM turn (>= 5 words) sampled per dialogue from 300 dialogues.
        Group = dialogue_id.

Hygiene (nothing silently dropped; see training_pool_v2.excluded.csv):
  * de-duplicate on normalise_text(); identical text with conflicting labels
    is excluded entirely;
  * remove any row overlapping the FROZEN evaluation set
    (data/real_world_test_v1.csv) or the challenge suite
    (data/challenge_suite_v1.csv): exact normalised, skeleton, or skeleton
    token Jaccard >= 0.8.

The frozen evaluation set is read ONLY to remove overlapping training rows.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import sys
import urllib.request
from collections import Counter
from pathlib import Path
from typing import Dict, List, Tuple

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from satyalens_analysis.text_classifier import (  # noqa: E402
    find_training_overlap,
    load_dataset,
    load_evaluation_dataset,
    normalise_text,
)

SEED = 20261024
MWOZ_DIALOGUES = 300
MIN_WORDS = 5

SYN_CSV = REPO / "data" / "synthetic_financial_messages_v1.csv"
FROZEN_EVAL = REPO / "data" / "real_world_test_v1.csv"
CHALLENGE = REPO / "data" / "challenge_suite_v1.csv"

R115 = {
    "repo": "Ridham115/indian-scam-sms-synthetic-audited",
    "revision": "45e92c38ba20e973ef3ff5d1893a0a710f622018",
    "path": "data/synthetic_audited.csv",
    "sha256": "45bde5f156a1a42698bab209e32bcd41b3639013d772f644cc3208ed39fb61e2",
    "local": REPO / "data" / "raw" / "ridham115_indian_scam_sms" / "synthetic_audited.csv",
}
MWOZ = {
    "repo": "budzianowski/multiwoz",
    "commit": "fe0c8e65cfcd8462bd33c86e35f21addc84ca82b",
    "path": "data/MultiWOZ_2.2/train/dialogues_001.json",
    "sha256": "895a8109bf01fa5ecf15ccdbd2dfe1628bd923f6b61dcd2e26b10ee5076a1596",
    "local": REPO / "data" / "raw" / "multiwoz_2_2" / "dialogues_001.json",
}
R115_GENERATORS = ("groq/openai/gpt-oss-120b",)
R115_LABELS = {"scam": "suspicious", "safe": "legitimate"}


def _fetch(url: str, dest: Path, sha256: str) -> bytes:
    if not dest.is_file():
        dest.parent.mkdir(parents=True, exist_ok=True)
        print(f"Downloading {url}")
        with urllib.request.urlopen(url, timeout=180) as resp:  # noqa: S310
            dest.write_bytes(resp.read())
    data = dest.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != sha256:
        raise SystemExit(f"SHA-256 mismatch for {dest}: expected {sha256}, got {actual}")
    return data


def load_r115(data: bytes) -> Tuple[List[Dict], List[Dict]]:
    rows, excluded = [], []
    reader = csv.DictReader(data.decode("utf-8").splitlines())
    for line_no, r in enumerate(reader, start=2):
        base = {"source": "R115", "source_ref": f"{r['row_id']} (line {line_no})", "text": r["text"].strip()}
        if r["generator"] not in R115_GENERATORS:
            excluded.append({**base, "outcome": "excluded_generator",
                             "reason": f"generator {r['generator']} excluded pending output-terms review"})
            continue
        if not base["text"] or r["label"] not in R115_LABELS:
            excluded.append({**base, "outcome": "rejected", "reason": f"empty text or label {r['label']!r}"})
            continue
        label = R115_LABELS[r["label"]]
        rows.append({**base, "label": label, "group": f"R115:{r['label']}:{r['topic']}:{r['language']}"})
    return rows, excluded


def load_mwoz(data: bytes, n_dialogues: int = MWOZ_DIALOGUES, seed: int = SEED) -> List[Dict]:
    dialogues = sorted(json.loads(data.decode("utf-8")), key=lambda d: d["dialogue_id"])
    rng = random.Random(seed)
    rng.shuffle(dialogues)
    rows = []
    for d in dialogues[:n_dialogues]:
        for speaker in ("USER", "SYSTEM"):
            turns = [t["utterance"].strip() for t in d["turns"]
                     if t["speaker"] == speaker and len(t["utterance"].split()) >= MIN_WORDS]
            if turns:
                rows.append({"source": "MWOZ", "source_ref": f"{d['dialogue_id']}:{speaker}",
                             "text": rng.choice(turns), "label": "legitimate",
                             "group": f"MWOZ:{d['dialogue_id']}"})
    return rows


def build_pool(candidates: List[Dict], protected_texts: List[str]) -> Tuple[List[Dict], List[Dict], Dict]:
    """De-duplicate and remove overlap with protected (evaluation/validation) texts."""
    excluded: List[Dict] = []
    labels_by_norm: Dict[str, set] = {}
    for c in candidates:
        labels_by_norm.setdefault(normalise_text(c["text"]), set()).add(c["label"])
    seen: Dict[str, str] = {}
    unique: List[Dict] = []
    for c in candidates:
        key = normalise_text(c["text"])
        if len(labels_by_norm[key]) > 1:
            excluded.append({**c, "outcome": "ambiguous", "reason": "identical text with conflicting labels"})
        elif key in seen:
            excluded.append({**c, "outcome": "duplicate", "reason": f"duplicate of {seen[key]}"})
        else:
            seen[key] = f"{c['source']}:{c['source_ref']}"
            unique.append(c)

    overlap = find_training_overlap(list(enumerate(c["text"] for c in unique)), protected_texts)
    hit = {i: kind for kind in ("exact_normalised", "skeleton", "token_jaccard") for i in overlap[kind]}
    kept = []
    for i, c in enumerate(unique):
        if i in hit:
            excluded.append({**c, "outcome": "eval_overlap",
                             "reason": f"overlaps frozen evaluation set or challenge suite ({hit[i]})"})
        else:
            kept.append(c)
    return kept, excluded, {k: len(overlap[k]) for k in ("exact_normalised", "skeleton", "token_jaccard")}


def main() -> None:
    argparse.ArgumentParser(description="Build data/training_pool_v2.csv").parse_args()
    r115_bytes = _fetch(f"https://huggingface.co/datasets/{R115['repo']}/resolve/{R115['revision']}/{R115['path']}",
                        R115["local"], R115["sha256"])
    mwoz_bytes = _fetch(f"https://raw.githubusercontent.com/{MWOZ['repo']}/{MWOZ['commit']}/{MWOZ['path']}",
                        MWOZ["local"], MWOZ["sha256"])

    syn = [{"source": "SYN", "source_ref": f"line {e.row}", "text": e.text, "label": e.label,
            "group": f"SYN:{e.group}"} for e in load_dataset(SYN_CSV)]
    r115, r115_excluded = load_r115(r115_bytes)
    mwoz = load_mwoz(mwoz_bytes)

    protected = [e.text for e in load_evaluation_dataset(FROZEN_EVAL)] + \
                [e.text for e in load_evaluation_dataset(CHALLENGE)]
    pool, excluded, overlap_counts = build_pool(syn + r115 + mwoz, protected)
    excluded = r115_excluded + excluded

    out = REPO / "data" / "training_pool_v2.csv"
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["id", "text", "label", "group", "source", "source_ref"])
        w.writeheader()
        for i, r in enumerate(pool):
            w.writerow({"id": f"TP2-{i:05d}", **{k: r[k] for k in ("text", "label", "group", "source", "source_ref")}})
    exc = out.with_name("training_pool_v2.excluded.csv")
    with exc.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["source", "source_ref", "label", "outcome", "reason", "text"])
        w.writeheader()
        for r in excluded:
            w.writerow({k: r.get(k, "") for k in ("source", "source_ref", "label", "outcome", "reason", "text")})

    by_src = {s: dict(Counter(r["label"] for r in pool if r["source"] == s)) for s in ("SYN", "R115", "MWOZ")}
    summary = {
        "candidates": {"SYN": len(syn), "R115_total_rows": len(r115) + len(r115_excluded),
                       "R115_used": len(r115), "MWOZ": len(mwoz)},
        "pool_rows": len(pool),
        "pool_class_counts": dict(Counter(r["label"] for r in pool)),
        "pool_by_source": by_src,
        "groups": len({r["group"] for r in pool}),
        "excluded_outcomes": dict(Counter(e["outcome"] for e in excluded)),
        "eval_overlap_by_kind": overlap_counts,
    }
    provenance = {
        "name": "satyalens-training-pool",
        "version": "2",
        "synthetic": "partial",
        "role": "training only; never evaluation",
        "sources": {
            "SYN": {"file": SYN_CSV.name, "synthetic": True, "licence": "project-created (MIT repository)"},
            "R115": {"title": "Indian Scam SMS (synthetic, audited)", "url": f"https://huggingface.co/datasets/{R115['repo']}",
                     "revision": R115["revision"], "file": R115["path"], "sha256": R115["sha256"],
                     "retrieved": "2026-10-24", "licence": "CC BY 4.0 (dataset card metadata)",
                     "attribution": "Ridham115, 'Indian Scam SMS (synthetic, audited)', Hugging Face dataset "
                                    f"{R115['repo']}, revision {R115['revision'][:12]}, CC BY 4.0.",
                     "synthetic": True, "generators_used": list(R115_GENERATORS),
                     "label_mapping": {"scam": "suspicious", "safe": "legitimate"},
                     "label_basis": "Source rubric (label_rubric.md): scam = deception to obtain money/OTP/"
                                    "credentials/risky action; safe = informational or personal incl. genuine "
                                    "OTP alerts. Mostly LLM-audited, partly unreviewed.",
                     "note": "Card warns generator-provider terms still apply; Gemini rows excluded."},
            "MWOZ": {"title": "MultiWOZ 2.2", "url": f"https://github.com/{MWOZ['repo']}", "commit": MWOZ["commit"],
                     "file": MWOZ["path"], "sha256": MWOZ["sha256"], "retrieved": "2026-10-24",
                     "licence": "MIT — Copyright (c) 2019 Paweł Budzianowski",
                     "citation": "Budzianowski et al. 2018, EMNLP; Zang et al. 2020 (MultiWOZ 2.2)",
                     "synthetic": False, "label_mapping": {"*": "legitimate"},
                     "label_basis": "Human-written Wizard-of-Oz booking dialogues; benign by construction.",
                     "sampling": f"{MWOZ_DIALOGUES} dialogues, one USER + one SYSTEM turn (>= {MIN_WORDS} words) "
                                 f"each, seed {SEED}"},
        },
        "independence": "No source derives from Mishra & Soni 2022, UCI SMS Spam or NUS SMS Corpus "
                        "(the frozen evaluation set's sources); row-level overlap was also removed.",
        "limitations": [
            "Suspicious examples are entirely synthetic (SYN + LLM-generated R115); no real scam SMS "
            "with a verifiable licence and no evaluation-source contamination was found.",
            "MWOZ is booking dialogue, not SMS; it may teach topic shortcuts (restaurants, trains).",
            "R115 Devanagari rows are tokenised imperfectly by the letters-only token pattern.",
            "R115 labels are LLM-audited and mostly unreviewed by humans.",
        ],
        **summary,
    }
    provenance["csv_sha256"] = hashlib.sha256(out.read_bytes()).hexdigest()
    out.with_suffix(".provenance.json").write_text(json.dumps(provenance, indent=2, ensure_ascii=False),
                                                   encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
